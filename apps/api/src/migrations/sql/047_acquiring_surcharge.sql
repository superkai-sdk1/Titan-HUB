-- 047: кто оплатил эквайринговую надбавку СБП (8%).
--
-- Раньше система НЕ фиксировала, доплатил ли клиент комиссию эквайринга 8%
-- поверх товарной суммы (вопрос «Добавить комиссию 8%?» на экране СБП). В отчётах
-- эквайринг всегда списывался как потеря ВЛАДЕЛЬЦА (8% от всех СБП-переводов), даже
-- когда надбавку оплатил ПОКУПАТЕЛЬ — тогда для владельца это не потеря.
--
-- acquiring_surcharge = сумма надбавки, которую фактически доплатил клиент (>0 ⇒
-- комиссию закрыл покупатель, потерей владельца НЕ считается). 0 ⇒ надбавки не было,
-- 8% удержал банк из выручки владельца (потеря владельца).
--
-- НЕРАЗРУШАЮЩЕ: только ADD COLUMN с DEFAULT 0. Историческим чекам ставится 0
-- (поведение прежних отчётов сохраняется — задним числом плательщика не определить).
ALTER TABLE checks ADD COLUMN IF NOT EXISTS acquiring_surcharge numeric(12,2) NOT NULL DEFAULT 0;
