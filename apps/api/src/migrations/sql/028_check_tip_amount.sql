-- Чаевые по QR/СБП: гость на планшете может добавить чаевые поверх суммы чека.
-- Сумма хранится на чеке (durable), чтобы webhook Platega мог:
--   1) валидировать увеличенную сумму к оплате (иначе AMOUNT_MISMATCH),
--   2) зафиксировать фактически уплаченные чаевые.
-- Выручка магазина (платёж/транзакция) по-прежнему пишется на БАЗОВУЮ сумму
-- товаров — чаевые учитываются отдельно этим полем.
ALTER TABLE checks
  ADD COLUMN IF NOT EXISTS tip_amount numeric(12, 2) NOT NULL DEFAULT 0;
