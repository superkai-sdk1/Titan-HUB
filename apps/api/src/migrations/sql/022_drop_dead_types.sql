-- Удаляем мёртвый Postgres-enum `client_tier`.
--
-- Миграция 021 перевела обе колонки, которые ссылались на этот тип
-- (profiles.client_tier и client_discount_rules.client_tier), в text. Поэтому тип
-- больше ни на что не завязан и остаётся «висящим» — из-за него drizzle-kit push
-- видит дрейф (schema больше не объявляет clientTierEnum, а тип в БД ещё есть).
--
-- Идемпотентно: IF EXISTS подавляет ошибку, если типа уже нет. DROP TYPE
-- транзакционно-безопасен (раннер оборачивает файл в транзакцию).
--
-- ВАЖНО: CASCADE сознательно НЕ используем — если по какой-то причине на тип ещё
-- есть зависимость (колонка не была сконвертирована), миграция должна УПАСТЬ, а не
-- молча удалить зависимый объект. В этом случае нужно сперва доконвертировать
-- колонку в text (как в 021) и только потом дропать тип.
DROP TYPE IF EXISTS client_tier;

