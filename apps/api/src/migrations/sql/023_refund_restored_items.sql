-- Колонка refunds.restored_items: фактически восстановленный на склад сток
-- данным возвратом — [{ itemId, quantity }].
--
-- Зачем: восстановление стока при возврате раньше ограничивалось только общим
-- количеством проданного по чеку, без учёта того, что предыдущие частичные
-- возвраты уже вернули часть на склад. Из-за этого повторные частичные возвраты
-- могли восстановить сток СВЕРХ проданного. Теперь cap = sold − alreadyRestored,
-- где alreadyRestored суммируется по restored_items всех предыдущих возвратов чека.
--
-- Идемпотентно: IF NOT EXISTS подавляет ошибку при повторном прогоне. DEFAULT '[]'
-- даёт старым строкам пустой массив (они не участвуют в alreadyRestored).
ALTER TABLE refunds ADD COLUMN IF NOT EXISTS restored_items jsonb DEFAULT '[]'::jsonb;
