-- 075: фактически начисленные бонусы за чек.
--
-- checks.bonus_awarded — сколько бонусов РЕАЛЬНО начислено клиенту при закрытии
--   чека (POS /pay, СБП-вебхук Platega, settle). 0 — ничего не начислено (бонусы
--   выключены, сумма ниже минимальной, оплата в долг без начисления, нет клиента).
-- Возврат откатывал floor(итог × ТЕКУЩАЯ ставка) независимо от того, начислялись ли
-- бонусы вообще (и по какой ставке) → списывал клиенту бонусы, которых он не получал.
-- Теперь откат считается от этого значения. NULL — старые чеки (до 075): для них
-- возврат работает по прежней формуле.
-- Идемпотентно, на всех БД клубов.

ALTER TABLE checks ADD COLUMN IF NOT EXISTS bonus_awarded numeric(12, 2);
