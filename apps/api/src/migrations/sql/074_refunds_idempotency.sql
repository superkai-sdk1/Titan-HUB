-- 074: идемпотентность возвратов.
--
-- POST /refunds не имел защиты от повтора: после таймаута клиента (сервер ещё
-- обрабатывает возврат за advisory-lock чека) приложение сверялось с чеком сразу,
-- не видело возврата и предлагало оформить его ещё раз → двойной возврат денег/склада.
-- Клиент теперь шлёт ключ идемпотентности; повтор с тем же ключом возвращает уже
-- записанный возврат.
-- ПОЛНЫЙ уникальный индекс (как у transactions, миграция 045): NULL'ы различны,
-- старые возвраты без ключа не конфликтуют.
-- Идемпотентно, на всех БД клубов.

ALTER TABLE refunds ADD COLUMN IF NOT EXISTS idempotency_key text;

CREATE UNIQUE INDEX IF NOT EXISTS refunds_idempotency_key_uniq
  ON refunds (idempotency_key);
